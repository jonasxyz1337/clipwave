const { contextBridge, ipcRenderer, webUtils } = require('electron');
const call = async (ch, ...a) => { const r = await ipcRenderer.invoke(ch, ...a); if (!r.ok) throw new Error(r.error); return r.data; };
contextBridge.exposeInMainWorld('api', {
  env: () => call('env'),
  loadState: () => call('state:load'),
  saveState: (s) => call('state:save', s),
  importUrl: (u, r) => call('video:url', u, r),
  importFile: () => call('video:file'),
  importPath: (p) => call('video:path', p),
  pathOf: (f) => webUtils.getPathForFile(f),
  transcribe: (o) => call('whisper:run', o),
  exportBatch: (j) => call('export:run', j),
  cancelExport: () => call('export:cancel'),
  pickDir: () => call('dir:pick'),
  open: (p) => call('shell:open', p),
  show: (p) => call('shell:show', p),
  exists: (p) => call('fs:exists', p),
  elevenConnect: () => call('eleven:connect'),
  elevenStop: () => call('eleven:stop'),
  elevenCheck: (k) => call('eleven:check', k),
  storageInfo: (o) => call('storage:info', o),
  storageClean: (o) => call('storage:clean', o),
  purgeVideo: (f) => call('video:purge', f),
  updateCheck: () => call('update:check'),
  updateInstall: () => call('update:install'),
  updateState: () => call('update:state'),
  pickSound: () => call('sound:pick'),
  onEvent: (cb) => ipcRenderer.on('evt', (_e, d) => cb(d)),
});
